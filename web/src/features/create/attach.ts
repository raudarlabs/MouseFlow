/* Текстовые файлы, приложенные к цели.
 *
 * ЧТО ЭТО ТАКОЕ, ОДНОЙ ФРАЗОЙ: содержимое файла становится ЧАСТЬЮ ТОГО, О ЧЁМ ПОПРОСИЛИ, - ровно как если
 * бы человек вставил его в поле руками. Не отдельное поле, не вложение, которое куда-то «прилагается».
 *
 * ПОЧЕМУ ТАК, А НЕ ОТДЕЛЬНЫМ ПОЛЕМ. Цель едет через очередь (`run_queue`), через три реализации цикла
 * (`api/_brain.mjs`, `api/_step.mjs`, `web/src/lib/desktop-engine.ts`) и ложится в `user_run.goal`, откуда
 * её читают журнал, поиск и навыки. Новое поле рядом с ней пришлось бы провести через всё это и через
 * расширение, и до тех пор половина путей молча теряла бы вложение - то есть прогон шёл бы без того, что
 * человек приложил, и выглядел бы при этом нормально. Склейка в цель работает на каждом пути с первого дня
 * и ничего не теряет.
 *
 * ЧТО ЭТО СТОИТ, названо здесь, а не умолчано: цель с приложенным файлом уходит модели НА КАЖДОМ ШАГЕ,
 * потому что цель - это то, что модель читает каждый раз. Двадцать килобайт текста в цели - это двадцать
 * килобайт на каждый из тридцати шагов. Отсюда потолок ниже, и он же - тот предел, который путь очереди
 * СОХРАНЯЕТ (`api/_mcp-worker.mjs` кладёт в `user_run.goal` первые 4000 знаков). Потолок здесь равен ему
 * НАРОЧНО: если бы он был больше, прогон, запущенный из Create, помнил бы цель целиком, а тот же прогон,
 * поднятый расписанием, - обрезанную, и разница бы нигде не всплыла.
 *
 * ТЕКСТ ПРОВЕРЯЕТСЯ, А НЕ ПРЕДПОЛАГАЕТСЯ ПО РАСШИРЕНИЮ. `.txt` бывает у чего угодно, а .docx - это zip:
 * положить его содержимое в цель значит отправить модели мусор и списать за него деньги. Признак - нулевой
 * байт и доля управляющих знаков, то есть свойство САМОГО содержимого.
 */

/* Сколько знаков может занять вся цель вместе с приложенным - ОДНО число на все четыре места, которые
 * его знают, и живёт оно в мозге (api/_brain.mjs), а не здесь. Раньше их было три, они совпадали, и
 * совпадение держалось на комментарии; теперь совпадение держится на импорте. Почему потолок вырос с
 * 4000 до 20000 - там же, у самой константы: первое сообщение попало в кешируемый префикс. */
export { GOAL_MAX } from '../../../../api/_brain.mjs';
import { GOAL_MAX } from '../../../../api/_brain.mjs';

/** Один файл не читается дальше этого - смысла нет, в цель он всё равно не поместится. */
const READ_MAX = GOAL_MAX;

/** Столько файлов за раз. Больше - это уже не «приложить контекст», а «загрузить папку». */
export const FILES_MAX = 5;

export interface Attached {
  /** Собственный идентификатор: два файла могут называться одинаково. */
  id: string;
  name: string;
  /** Прочитанный текст, уже обрезанный по READ_MAX. */
  text: string;
  /** Байты НА ДИСКЕ, до обрезки: человек должен видеть, что файл был больше. */
  bytes: number;
  /** Обрезали ли при чтении. */
  clipped: boolean;
}

/** Нулевой байт. Именем и через escape - см. комментарий у его единственного использования ниже. */
const NUL = '\u0000';

/** Похоже ли это на текст. Смотрит на содержимое, а не на имя. */
export const looksLikeText = (text: string): boolean => {
  if (!text) return true;
  /* Нулевой байт в тексте не встречается, а в любом двоичном формате встречается в первых же килобайтах. */
  const head = text.slice(0, 4096);
  /* ЭКРАНИРОВАННЫМ, а не самим знаком - тот же случай, что с BOM в web/src/lib/csv.ts, и здесь он хуже:
   * настоящий нулевой байт посреди исходника невидим, строка читается как `includes('')`, а это выражение
   * истинно для ЛЮБОГО текста - то есть проверка молча стала бы «всё двоичное». */
  if (head.includes(NUL)) return false;
  /* Доля знаков, которых в тексте быть не должно: управляющие, кроме табуляции, перевода строки и возврата
   * каретки. Один такой знак - ещё не приговор (бывает в экспортах), а каждый десятый - уже не текст. */
  let odd = 0;
  for (const ch of head) {
    const code = ch.codePointAt(0) ?? 0;
    if (code < 32 && code !== 9 && code !== 10 && code !== 13) odd += 1;
  }
  return odd / head.length < 0.1;
};

/** Прочитать один файл. Отказ - строка с причиной, которую можно показать: молчаливый пропуск файла хуже. */
export async function readTextFile(file: File): Promise<{ one: Attached } | { error: string }> {
  let raw: string;
  try {
    raw = await file.text();
  } catch (e) {
    return { error: `${file.name} could not be read: ${e instanceof Error ? e.message : 'unknown error'}` };
  }
  if (!looksLikeText(raw)) {
    return {
      error: `${file.name} is not a text file — it looks binary. A .docx or a .pdf is a container, not text; `
        + 'export it as .txt or .md first.',
    };
  }
  const text = raw.slice(0, READ_MAX);
  return {
    one: {
      id: `${Date.now()}-${Math.random().toString(36).slice(2, 8)}`,
      name: file.name,
      text,
      bytes: file.size,
      clipped: raw.length > text.length,
    },
  };
}

/* КАК ПРИЛОЖЕННОЕ ВЫГЛЯДИТ В ЦЕЛИ.
 *
 * Имя файла названо, и границы блока видны: модель должна отличать «вот что мне велели сделать» от «вот
 * данные, о которых речь», иначе строка из csv читается как указание. Заборчик из дефисов, а не разметка -
 * цель это обычный текст, который потом читает человек в журнале. */
const block = (one: Attached): string =>
  `----- ${one.name} -----\n${one.text.trim()}\n----- end of ${one.name} -----`;

/** Цель целиком: что напечатано, плюс приложенное. Это ровно та строка, которая уедет в прогон. */
export function goalWith(typed: string, files: Attached[]): string {
  const said = typed.trim();
  if (!files.length) return said;
  return [said, ...files.map(block)].filter(Boolean).join('\n\n');
}

/** Сколько знаков осталось до потолка. Отрицательное - перебор, и запускать нельзя. */
export const roomLeft = (typed: string, files: Attached[]): number =>
  GOAL_MAX - goalWith(typed, files).length;

/** Байты словами, для чипа рядом с именем файла. */
export const sizeSaid = (bytes: number): string =>
  (bytes < 1024 ? `${bytes} B` : bytes < 1024 * 1024 ? `${Math.round(bytes / 1024)} kB`
    : `${(bytes / 1024 / 1024).toFixed(1)} MB`);

/* ОБРАТНАЯ ОПЕРАЦИЯ: цель, уже уехавшую в прогон, разобрать назад на набранное и приложенное.
 *
 * Нужна ровно в одном месте - когда прошлую задачу открывают заново, чтобы повторить или поправить. Без
 * неё в поле ложится весь текст вместе с заборчиками, и человек, который хотел поменять одно слово,
 * получает три экрана csv в композере.
 *
 * ЧТО ЕСЛИ ЧЕЛОВЕК САМ НАПЕЧАТАЛ ТАКИЕ ЖЕ ЧЁРТОЧКИ. Тогда его текст уедет в чип с именем файла - и это
 * единственный способ ошибиться, который здесь есть. Он не теряет ничего: содержимое целиком остаётся в
 * цели, `goalWith` соберёт ту же строку обратно, и прогон уйдёт тот же. Поэтому закрывающая строка обязана
 * называть ТО ЖЕ имя, что открывающая: совпасть случайно дважды заметно труднее, чем один раз.
 */
export function splitGoal(said: string): { typed: string; files: Attached[] } {
  const files: Attached[] = [];
  const typed = String(said || '').replace(
    /-{5} (.+?) -{5}\n([\s\S]*?)\n-{5} end of \1 -{5}/g,
    (_whole, name: string, body: string) => {
      files.push({
        id: `${Date.now()}-${files.length}-${Math.random().toString(36).slice(2, 6)}`,
        name,
        text: body,
        /* Байты СОДЕРЖИМОГО, а не файла на диске: настоящего размера в цели не осталось, и придумать его
         * значило бы показать число, которого никто не мерил. */
        bytes: new TextEncoder().encode(body).length,
        clipped: false,
      });
      return '';
    },
  ).trim();
  return { typed, files };
}
