/* Кто звонит из панели агента — и почему там не спрашивают пароль.
 *
 * ЧТО БЫЛО НЕ ТАК. Панель (SPLIT-PLAN §7, шаг 16) - это WKWebView, а у него своё хранилище кук, отдельно
 * от Safari. Первое, что встречал человек по горячей клавише, - экран входа с кодом по SMS. Он просил то,
 * что у нас УЖЕ ЕСТЬ: агент привязан к аккаунту токеном устройства, иначе он не брал бы работу.
 *
 * ПОЭТОМУ ТОКЕН ПРИЕЗЖАЕТ СВЕРХУ. Агент кладёт его в `window.__mouseflow` при загрузке страницы, и только
 * когда адрес - это его же аккаунт (см. Panel.build в agent/mouseflow-agent.swift). `whoIsCalling` уже
 * умеет читать такой токен из заголовка Authorization - это один из трёх способов быть собой, и он же
 * работает у расширения. Ничего нового не изобретается: меняется только то, ЧЕМ панель предъявляет
 * аккаунт, а не как он проверяется.
 *
 * ПОЧЕМУ ЭТО ОТДЕЛЬНЫЙ ФАЙЛ, А НЕ ПАРАМЕТР У КАЖДОГО ВЫЗОВА. Запросов из панели несколько - план, речь,
 * очередь, - и все они живут в коде, который вызывается ещё и из обычной вкладки. Аргумент «а это из
 * панели?» пришлось бы протащить через три файла, и первый же новый вызов его бы забыл. Здесь ответ
 * общий: в браузере пусто, в панели заголовок, и никто из вызывающих про это не думает.
 *
 * В ОБЫЧНОЙ ВКЛАДКЕ ЭТО НИЧЕГО НЕ МЕНЯЕТ: `window.__mouseflow` там нет, функция возвращает пустой объект,
 * и всё продолжает ходить кукой.
 */

declare global {
  interface Window {
    /** Ставит агент, и только на своём же адресе. Отсутствует во всяком обычном браузере. */
    __mouseflow?: { token?: string };
    /** Мост WKWebView. Есть только внутри панели; в браузере его нет, и это способ отличить одно от другого. */
    webkit?: { messageHandlers?: { mouseflow?: { postMessage: (body: unknown) => void } } };
  }
}

/** Токен устройства, если эту страницу показывает панель агента. */
export function panelToken(): string | null {
  try {
    const said = window.__mouseflow?.token;
    /* Форма проверяется, а не принимается на слово: подлинность знает только база, но `mf_` - это то,
     * что отличает наш токен от чего угодно другого, что могло попасть в это поле. */
    return typeof said === 'string' && /^mf_[A-Za-z0-9_-]{8,200}$/.test(said) ? said : null;
  } catch (_) {
    /* Песочница без window - ничего страшного, просто не панель. */
    return null;
  }
}

/** Заголовки, которыми панель предъявляет аккаунт. Пусто в обычной вкладке. */
export function asPanel(): Record<string, string> {
  const token = panelToken();
  return token ? { authorization: `Bearer ${token}` } : {};
}

/* ВЫСОТА - ЕДИНСТВЕННОЕ, ЧТО СТРАНИЦА ГОВОРИТ ОКНУ.
 *
 * Панель без хрома должна быть ровно такой, как её содержимое: одна строка, пока не начали печатать, и
 * выше - когда появился план. Угадать это снаружи нельзя, поэтому меряет тот, кто знает, - страница.
 *
 * ОДНО СООБЩЕНИЕ И НИЧЕГО БОЛЬШЕ. Мост из веб-страницы в нативное окно - это не место для «а что ещё
 * отсюда можно попросить»: чем он уже, тем меньше о нём надо думать. Агент сверяет имя и проверяет число.
 *
 * В браузере моста нет, и функция молчит: страница /panel открывается и вкладкой тоже.
 */
export function tellPanelHeight(px: number) {
  try {
    const post = window.webkit?.messageHandlers?.mouseflow?.postMessage;
    if (!post) return;
    window.webkit!.messageHandlers!.mouseflow!.postMessage({ height: Math.ceil(px) });
  } catch (_) {
    /* Не панель, или мост закрыт - высота просто не поменяется. */
  }
}

/** Внутри ли мы нативной панели. Читается как условие, а не как проверка наличия функции. */
export const inPanel = (): boolean => !!window.webkit?.messageHandlers?.mouseflow;
