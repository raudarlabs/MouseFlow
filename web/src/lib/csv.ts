/* Таблица на экране - в файл, который откроется в Excel.
 *
 * Приём взят из нашего же MCPGateway (`lib/csv.ts` там, audit-лог) - владелец показал его 2026-09-18 как
 * образец для журнала. Переписан здесь, а не скопирован: тот проект на других токенах и другой сборке, и
 * общего пакета между ними нет. Три решения оттуда стоит сохранить именно такими, потому что каждое
 * закрывает свой способ отдать файл, который выглядит целым и не читается.
 *
 * СПЕЦИФИКАЦИЯ (RFC 4180), а не «склеить через запятую». Кавычка внутри значения удваивается, а значение,
 * в котором есть запятая, кавычка или перевод строки, берётся в кавычки целиком. Цель прогона - это текст,
 * который человек печатал руками; запятая в нём - обычное дело, и без экранирования одна такая строка
 * сдвигает все столбцы правее себя, причём ровно в той строке, из-за которой файл и открыли.
 *
 * CRLF между строками, а не LF: с одним LF Excel на Windows читает файл как одну строку.
 *
 * BOM В НАЧАЛЕ. Без него Excel открывает UTF-8 в системной кодировке, и русские имена прогонов
 * превращаются в «ÐŸÑ€Ð¾Ð²ÐµÑ€ÑŒ». Файл при этом не сломан - сломано только то, что видит человек, и
 * винить он будет нас.
 */

/* U+FEFF ЭКРАНИРОВАННЫМ, а не самим знаком.
 *
 * Сначала он попал сюда буквальным символом - невидимым, нулевой ширины, посреди строки кода. Читать такое
 * нельзя: строка выглядит как `['' + csv]`, и следующий, кто её увидит, уберёт «лишнюю пустую строку». Имя
 * плюс escape говорят, что это за знак и зачем он тут, и grep по BOM его находит. */
const BOM = '\uFEFF';

export type CsvColumn<T> = {
  header: string;
  get: (row: T) => unknown;
};

const cell = (v: unknown): string => {
  if (v === null || v === undefined) return '';
  const s = typeof v === 'string' ? v
    : typeof v === 'number' || typeof v === 'boolean' ? String(v)
      : JSON.stringify(v);
  return /[",\r\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
};

export function rowsToCsv<T>(rows: T[], columns: CsvColumn<T>[]): string {
  const head = columns.map((c) => cell(c.header)).join(',');
  const body = rows.map((row) => columns.map((c) => cell(c.get(row))).join(',')).join('\r\n');
  /* Одна шапка, когда строк нет: пустой файл нельзя отличить от неудавшейся выгрузки, а файл с одной
   * шапкой говорит «выгрузилось, и в выгрузке ничего не было». */
  return body ? `${head}\r\n${body}` : head;
}

/** Отдать строку файлом. Ссылка создаётся, нажимается и убирается - в браузере это единственный способ
 *  начать скачивание из кода, и `revokeObjectURL` возвращает память сразу, а не к закрытию вкладки. */
export function downloadCsv(filename: string, csv: string): void {
  const blob = new Blob([BOM + csv], { type: 'text/csv;charset=utf-8' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  a.remove();
  URL.revokeObjectURL(url);
}

/** Имя файла со отметкой времени, годной для файловой системы: двоеточий в нём быть не может. */
export const stampedName = (base: string): string =>
  `${base}-${new Date().toISOString().replace(/[:.]/g, '-')}.csv`;
