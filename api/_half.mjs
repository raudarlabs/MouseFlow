/* КАКУЮ ПОЛОВИНУ ОТВЕТА СПРОСИЛИ У /api/insights - одно определение на маршрут, страницу и фикстуру.
 *
 * Маршрут отвечает сразу на два вопроса разных продуктов: ЧТО ДЕЛАЛ ЧЕЛОВЕК (записи, время по
 * приложениям, внимание, узоры - `user_flow` и дайджесты) и КАК ОТРАБОТАЛ АГЕНТ (прогоны, исходы, дни,
 * повторы, отказы - `user_run`). См. docs/SPLIT-PLAN.md §4.3.
 *
 * ПОЧЕМУ ОТДЕЛЬНЫМ ФАЙЛОМ, а не рядом с запросами в api/insights.js: это читает и подделка маршрута в
 * dev-режиме (web/src/dev/mock-api.ts). Второй список блоков там разошёлся бы с первым молча - фикстура,
 * отдающая блок, которого настоящий маршрут в этой половине не отдаёт, учит страницу рисовать то, что
 * никогда не приедет, и узнают об этом на живом аккаунте. Тот же приём, которым в api/ держатся в шаге
 * все прочие определения, общие для сервера и браузера.
 *
 * `totals`, `applications` и `unattributed` стоят В ОБОИХ списках НАРОЧНО. Это одно измеренное время,
 * сложенное из двух источников, и каждая половина приносит свою часть: спросив одну, получаешь её часть -
 * названную, а не молча уменьшенное число. `totals` при этом единственный блок, разрезанный ПО ПОЛЯМ:
 * пять полей о прогонах и два о записях всегда жили под одним именем, и разносить их по разным блокам
 * значило бы переименовать поля, которые читает каждый существующий вызывающий.
 */

export const BLOCKS = {
  did: ['totals', 'applications', 'unattributed', 'attention', 'actions', 'patterns',
    'previousBehaviour', 'digest'],
  ran: ['totals', 'byOutcome', 'byDay', 'previous', 'applications', 'unattributed',
    'repeated', 'slowestSteps', 'failures', 'skills'],
};

/** Что спросили, приведённое к трём словам. Всё непонятное - `both`: закладка с опечаткой должна
 *  показывать страницу целиком, а не половину и не ошибку. */
export const halfAsked = (raw) => {
  const said = String(raw == null ? '' : raw).trim().toLowerCase();
  return said === 'did' || said === 'ran' ? said : 'both';
};

/** Множество блоков, которые в этой половине есть. Одно на ответ, его потолки и его оговорки. */
export const blocksFor = (half) => {
  const asks = halfAsked(half);
  return new Set([
    ...(asks === 'ran' ? [] : BLOCKS.did),
    ...(asks === 'did' ? [] : BLOCKS.ran),
  ]);
};
