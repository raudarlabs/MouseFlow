-- Один мессенджер как входная дверь (SPLIT-PLAN §7.2, шаг 14a).
--
-- ПРИМЕНЕНА 2026-09-21, по явному разрешению владельца в чате - тем же порядком, что 022 и 023, - и
-- проверена `npm run migrate -- --list` (все 24 файла `applied`) и чтением information_schema: обе
-- таблицы на месте со всеми колонками.
--
-- И КОД РАБОТАЕТ БЕЗ НЕЁ - свойство, которое стоит сохранить, а не считать историей: api/telegram.js
-- ловит отсутствие таблицы и отвечает словами, «this deployment has no channel table yet». Не молчит и
-- не притворяется, что незнакомец заблокирован: отсутствие - не отказ. То же свойство, ради которого 022 могла неделю лежать неприменённой.
--
-- ПОЧЕМУ ДВЕ ТАБЛИЦЫ, А НЕ ОДНА. Они отвечают на разные вопросы и живут разное время. chat_sender - это
-- ПРАВО: кто этот человек и чей это аккаунт; живёт, пока его не отзовут. chat_draft - это ПРЕДЛОЖЕНИЕ:
-- один показанный план, который либо одобрят в ближайшие полчаса, либо он протухнет. Сложить их вместе
-- значило бы, что отзыв права стирает историю того, что предлагалось, а протухший план трогает право.
--
-- ПОЧЕМУ НЕ user_pref, КУДА ПРОСИЛОСЬ. Искать надо ПО ОТПРАВИТЕЛЮ: приходит telegram-id, и по нему надо
-- найти аккаунт. user_pref ключуется user_id - то есть поиск шёл бы сканированием значений, и первая же
-- таблица на десять тысяч строк превратила бы каждое входящее сообщение в полный проход. Направление
-- поиска - это и есть выбор ключа.

create table if not exists chat_sender (
  -- Канал назван, хотя сегодня он один: вторым будет не «ещё один столбец», а ещё одна строка.
  channel      text        not null,
  -- ИДЕНТИФИКАТОР, А НЕ ИМЯ (правило openclaw, и оно верное). Имя в телеграме меняет сам человек, и
  -- привязка по имени - это привязка к тому, что он может переписать.
  sender_id    text        not null,
  -- Чей это аккаунт. NULL, пока не спарен: строка существует раньше, чем право.
  user_id      uuid,
  -- pairing | allowed | blocked. Четвёртое состояние - отсутствие строки вовсе, то есть «впервые вижу»,
  -- и оно отличается от pairing тем, что человеку ещё ничего не сказали.
  state        text        not null default 'pairing',
  -- Куда отвечать. Хранится отдельно от sender_id, потому что в личке они совпадают, а вне лички нет.
  chat_id      text,
  first_at     timestamptz not null default now(),
  paired_at    timestamptz,
  seen_at      timestamptz,
  primary key (channel, sender_id)
);

-- Чей это чат - вторая сторона того же вопроса: «покажи мне все чаты этого аккаунта», для страницы
-- Connections, когда она появится, и для отзыва.
create index if not exists chat_sender_by_user on chat_sender (user_id) where user_id is not null;

create table if not exists chat_draft (
  -- Он же уезжает в callback_data кнопки, у которой потолок 64 байта. Отсюда короткий вид: `d<base36>`.
  id           text        primary key,
  channel      text        not null,
  sender_id    text        not null,
  user_id      uuid        not null,
  chat_id      text        not null,
  -- Ровно та строка, которая уедет в прогон, - уже собранная вместе с приложенным (api/_attach.mjs).
  -- Хранится целиком и заново не собирается: одобряют то, что показали, а показанное считалось из неё.
  goal         text        not null,
  -- План как его увидел человек. Нужен не для прогона - цикл о плане не знает, - а для ответа на вопрос
  -- «что именно я одобрил», когда прогон пошёл иначе.
  plan         jsonb,
  -- offered | approved | declined | expired. Нажатие по уже решённому черновику ничего не делает второй
  -- раз: телеграм повторяет callback при плохой связи, и вторая постановка в очередь - это второй прогон.
  state        text        not null default 'offered',
  -- Какую работу это породило, если породило. Чтобы ответ о том, чем кончилось, вернулся в тот же чат.
  job_id       text,
  created_at   timestamptz not null default now(),
  decided_at   timestamptz
);

-- Единственные два чтения: план по кнопке (по первичному ключу) и «чей чат ждёт ответа об этой работе».
create index if not exists chat_draft_by_job on chat_draft (job_id) where job_id is not null;
