-- Лист ожидания лендинга hivelink.si (2026-10-16). Маршрут - api/waitlist.js, правила - api/_waitlist.mjs.
--
-- НЕ ПРИМЕНЕНА. Применяется только по явному разрешению владельца, затем `npm run migrate -- --list`.
-- До применения маршрут отвечает 500 (вставке некуда писать) и сообщает об этом в отчёт об ошибках; на
-- остальное приложение она не влияет - ни одна другая таблица и ни один другой маршрут её не читают.
--
-- ПОЧЕМУ НЕ К АККАУНТУ. Человек из листа ожидания ещё никто: у него нет user_id, сессии и права что-либо
-- здесь читать. Поэтому в таблице нет user_id, и стирание аккаунта (api/account.js) её не трогает - там
-- нечего стирать по id. Убрать адрес из листа - вручную, по просьбе, одним delete по email.

-- ОДИН АДРЕС - ОДНА СТРОКА. email - первичный ключ, уже нормализованный (trim + нижний регистр, см.
-- normaliseEmail): уникальность на сырой строке пропустила бы «Ann@x.si» и «ann@x.si » как двух людей.
-- Повтор - `on conflict do nothing` и тот же 200, что новому: ответ не говорит, был ли адрес в листе.
--
-- ЧЕГО ЗДЕСЬ НАМЕРЕННО НЕТ - хэша IP. Он нужен ровно на час, для потолка, и живёт в waitlist_try ниже,
-- которая подметается. Держать его рядом с адресом навсегда значило бы хранить второй признак человека
-- без всякой цели: адрес и так лежит, а «с какого IP он пришёл» больше никому не понадобится.
create table if not exists waitlist (
  email      text        primary key check (length(email) between 3 and 254),
  -- Откуда пришёл. Сегодня только 'landing'; колонка - чтобы второй вход не пришлось угадывать по ref.
  source     text        not null default 'landing' check (length(source) <= 32),
  -- Сводка utm/referrer, которую собрал лендинг. Ограничена здесь же, а не только в коде: строка, которую
  -- присылает браузер, - это строка, которую может прислать кто угодно.
  ref        text        check (ref is null or length(ref) <= 200),
  created_at timestamptz not null default now()
);

-- «Сколько пришло и откуда» - единственный вопрос, который к листу задают, и он по времени.
create index if not exists waitlist_created on waitlist (created_at desc);

-- ПОПЫТКИ, ДЛЯ ПОТОЛКА. Не строки листа, а каждый принятый к рассмотрению запрос - новый адрес, повтор и
-- ловушка для ботов одинаково. Считать строки самого листа было бы проще и неверно: повтор их не
-- добавляет, и тогда «на каком запросе пришёл 429» отвечало бы, был ли адрес в листе раньше, - тот самый
-- ответ, который 200 для всех трёх случаев старается не давать.
--
-- ip_hash - HMAC от IP (IPv6 - от /64), ключ - серверный секрет (см. ipKey в api/_waitlist.mjs). Без ключа
-- хэш IPv4 обращается перебором за минуты: адресов всего четыре миллиарда.
--
-- КОРОТКАЯ ПАМЯТЬ, как у model_call (012): строки - свидетельство на окно в час, а не история.
-- Подметаются на том же пути, что и пишутся.
create table if not exists waitlist_try (
  ip_hash text        not null,
  at      timestamptz not null default now()
);

-- Единственный запрос: сколько с этого хэша с такого-то момента.
create index if not exists waitlist_try_window on waitlist_try (ip_hash, at desc);

-- И единственный другой: что уже достаточно старо, чтобы выбросить.
create index if not exists waitlist_try_old on waitlist_try (at);
