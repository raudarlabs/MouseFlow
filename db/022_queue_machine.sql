-- ПРИМЕНЕНА 2026-09-11, по явному разрешению владельца в чате - тем же порядком, что и 023: миграция
-- против продакшен-базы применяется только так, а потом проверяется `npm run migrate -- --list` (все 23
-- файла `applied`). До этого дня она пролежала написанной и непринятой, и код, который её читает, написан
-- так, что работает и БЕЗ неё - привязка просто не действует, и ни один прогон от этого не ломается. Это
-- свойство стоит сохранить: оно и есть причина, по которой её можно было безопасно не применять неделю.
--
-- ПОЧЕМУ ЭТА КОЛОНКА НУЖНА, ЕСЛИ user_case.machine УЖЕ ЕСТЬ. 021 положила её заранее, с честной запиской
-- «nothing reads it yet; it is here because the column is free today and a migration is not» - и она
-- описывает КЕЙС, то есть намерение: «этот кейс живёт на QA-VM». А очередь описывает РАБОТУ, и работа,
-- поставленная ночью, обязана помнить намерение на момент постановки: кейс, у которого утром сняли
-- привязку, не должен менять машину у задания, которое уже стоит в очереди и, может быть, уже кем-то
-- взято. Один и тот же довод, по которому расписание кейса везёт его `id`, а не копию утверждений, -
-- только повёрнутый в другую сторону: здесь копируется ровно то, что должно замереть.
--
-- ПОЧЕМУ NULL ЗНАЧИТ «ЛЮБАЯ», А НЕ «НИКАКАЯ». Иначе эта миграция в день применения остановила бы все
-- существующие задания: у них у всех будет NULL. Отсутствие привязки - это отсутствие требования, ровно
-- как absent у флагов агента значит «не сказано», а не «нет».
--
-- ИМЯ, А НЕ ССЫЛКА НА УСТРОЙСТВО. Забирающий уже присылает себя в теле claim'а как `worker` - это
-- `Environment.MachineName` у Windows-агента, - и claimed_by его записывает. Сверять надо ровно с тем, что
-- приезжает, а не с третьей сущностью: привязка, которую не с чем сличить в момент выбора строки, не
-- работает. Поэтому здесь text, а не идентификатор токена устройства, как предполагал план.
alter table run_queue add column if not exists machine text;

